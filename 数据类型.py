#数据类型分为数字型：整型，浮点型，布尔类型，非数值型：字符串，元组，列表，字典，集合
#数值型
num1 = 12
num2 = 12.1
num3 = True
print(type(num1))
print(type(num2))
print(type(num3))
#非数值型
str1 = "hello world"
tuple1 = (1,2,3,4,5)
list1 = [1,2,3,4,5]
dict1 = {"name":"zhangsan","age":18}
set1 = {1,2,3,4,5}
print(type(str1))
print(type(tuple1))
print(type(list1))
print(type(dict1))
print(type(set1))
